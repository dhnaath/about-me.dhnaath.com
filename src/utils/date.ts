import type { Language } from '../types';

export function formatLocalizedLetterDate(lang: Language, date: Date = new Date()): string {
  if (lang === 'id') {
    return new Intl.DateTimeFormat('id-ID', {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    }).format(date);
  }
  return new Intl.DateTimeFormat('en-US', {
    month: 'long',
    day: 'numeric',
    year: 'numeric',
  }).format(date);
}
